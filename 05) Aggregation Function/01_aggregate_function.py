import numpy as np

arr = np.array([1, 2, 3, 4, 5, 6])

print(f'Sum of array: {np.sum(arr)}')
print(f'Mean/Avg of array: {np.mean(arr)}')
print(f'Min value in array: {np.min(arr)}')
print(f'Index of min value in array: {np.argmin(arr)}')
print(f'Max value in array: {np.max(arr)}')
print(f'Index of max value in array: {np.argmax(arr)}')
print(f'Std. Deviation of array: {np.std(arr)}')
print(f'Product/Multiplication of array: {np.prod(arr)}')
print(f'Varience of array: {np.var(arr)}')
print(f'Median(Middle element) of array: {np.median(arr)}')

